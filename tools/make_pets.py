"""Converts the BookOrbit companion sprites (64x64 colour pixel art, JSON) to 1-bit images in src/pets_data.cpp.
usage: make_pets.py ASSETS_DIR [preview.png]   (ASSETS_DIR holds cat.json, dog.json, ...)"""
import json, sys, os

NAMES = ["cat", "dog", "rabbit", "owl", "penguin", "robot", "vampire", "dragon", "ghost", "mimic", "mummy", "witch", "skeleton", "candle", "alien", "claude", "dino"]
POSES = ["wait", "sleep", "ribbon", "party", "yawn", "read"]
BAYER = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]

def luminance(hexcolor):
    r, g, b = (int(hexcolor[i:i + 2], 16) for i in (0, 2, 4))
    return 0.3 * r + 0.59 * g + 0.11 * b

def convert(pet_json):
    palette = {k: luminance(v) for k, v in pet_json["palette"].items()}
    out = {}
    for pose in POSES:
        rows = pet_json["poses"][pose]
        bits = bytearray(512)
        for y in range(64):
            for x in range(64):
                c = rows[y][x]
                if c not in palette: continue  # transparent: white
                lum = palette[c]
                # dark pixels stay solid; mid tones are dithered; light ones vanish into the page
                black = lum < 110 or (lum < 215 and (lum - 110) / 105 * 16 < BAYER[y & 3][x & 3] * 0.9 + 0.5 and lum < 175)
                if black: bits[y * 8 + x // 8] |= 0x80 >> (x & 7)
        out[pose] = bytes(bits)
    return out

assets = sys.argv[1]
def sprite_file(name):  # the BookOrbit plugin sprites live in ASSETS_DIR; Claude's and the dino's are drawn by make_claude_json.py and make_dino_json.py next to this script
    path = os.path.join(assets, name + ".json")
    return path if os.path.exists(path) else os.path.join(os.path.dirname(__file__), name + ".json")

sprites = [convert(json.load(open(sprite_file(n)))) for n in NAMES]
with open(os.path.join(os.path.dirname(__file__), "..", "src", "pets_data.cpp"), "w") as f:
    f.write('// Generated by tools/make_pets.py from the BookOrbit KOReader plugin sprites. 64x64, 1 bit per pixel, 1 = black.\n')
    f.write('#include "pets.h"\n\nnamespace pets {\n')
    f.write('const char* const kNames[kCount] = {%s};\n' % ", ".join('"%s"' % n.capitalize() for n in NAMES))
    f.write('const uint8_t kSprites[kCount][kPoses][kBytes] = {\n')
    for s in sprites:
        f.write("  {\n")
        for pose in POSES:
            f.write("    {" + ",".join("0x%02x" % b for b in s[pose]) + "},  // " + pose + "\n")
        f.write("  },\n")
    f.write("};\n}  // namespace pets\n")
if len(sys.argv) > 2:
    from PIL import Image
    sheet = Image.new("L", (64 * 6 + 70, 66 * len(NAMES)), 255)
    for i, s in enumerate(sprites):
        for j, pose in enumerate(POSES):
            for y in range(64):
                for x in range(64):
                    if s[pose][y * 8 + x // 8] & (0x80 >> (x & 7)): sheet.putpixel((j * 64 + x, i * 66 + y), 0)
    sheet.save(sys.argv[2])
